def _split_list(value):
    value = value.replace(", and ", ", ").replace(" and ", ", ")
    return [item.strip() for item in value.split(",") if item.strip()]


def _api_name(label):
    return re.sub(r"[^A-Za-z0-9]+", "_", label).strip("_") + "__c"


def _class_name(title):
    words = re.findall(r"[A-Za-z0-9]+", title)
    return "".join(word[:1].upper() + word[1:] for word in words[:4])


def _context(project, week_number):
    project = dict(project)
    entities = _split_list(project["entities"])
    personas = _split_list(project["personas"])
    phases = _split_list(project["process"])
    primary = entities[0]
    transaction = entities[2] if len(entities) > 2 else entities[1]
    prefix = _class_name(project["title"])
    details = PROJECT_DETAILS[project["number"]]
    return {
        **project,
        **details,
        "week": week_number,
        "entities_text": ", ".join(entities),
        "personas_text": ", ".join(personas),
        "phases_text": ", ".join(phases),
        "primary": primary,
        "transaction": transaction,
        "primary_api": _api_name(primary),
        "transaction_api": _api_name(transaction),
        "prefix": prefix,
        "branch": f"week-{week_number:02d}-" + re.sub(r"[^a-z0-9]+", "-", project["industry"].lower()).strip("-"),
    }


def _format(value, context):
    if isinstance(value, str):
        return value.format(**context)
    if isinstance(value, list):
        return [_format(item, context) for item in value]
    if isinstance(value, dict):
        return {key: _format(item, context) for key, item in value.items()}
    return value


def _step(title, purpose, actions, checkpoint, evidence, commands=None, caution=None):
    return {
        "title": title,
        "purpose": purpose,
        "actions": actions,
        "checkpoint": checkpoint,
        "evidence": evidence,
        "commands": commands or [],
        "caution": caution,
    }


